// Command gen writes the product name values for the other build systems from the constants in package brand.
//
//	go run ./internal/shared/brand/gen -ts web/src/brand.generated.ts   TypeScript module for the web console
//	go run ./internal/shared/brand/gen -wix                             WiX command-line defines for the MSI build
package main

import (
	"flag"
	"fmt"
	"os"

	"github.com/auzring1/librepatch/internal/shared/brand"
)

func main() {
	ts := flag.String("ts", "", "write the TypeScript module to this file")
	winres := flag.String("winres", "", "write the Windows version-resource description (go-winres JSON) to this file")
	wix := flag.Bool("wix", false, "print `-d Name=Value` defines for `wix build`, one per line")
	flag.Parse()
	if *ts != "" {
		src := fmt.Sprintf("// Generated by internal/shared/brand (go generate). Do not edit.\nexport const PRODUCT_NAME = %q;\nexport const AGENT_NAME = %q;\nexport const COMPANY_NAME = %q;\n",
			brand.Name, brand.AgentName, brand.Company)
		if err := os.WriteFile(*ts, []byte(src), 0o644); err != nil { // #nosec G306 -- a source file
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	if *winres != "" {
		src := fmt.Sprintf(`{
  "RT_VERSION": {
    "#1": {
      "0000": {
        "fixed": {"file_version": "0.0.0.0", "product_version": "0.0.0.0"},
        "info": {
          "0409": {
            "CompanyName": %q,
            "FileDescription": %q,
            "InternalName": %q,
            "LegalCopyright": %q,
            "OriginalFilename": %q,
            "ProductName": %q,
            "ProductVersion": "0.0.0-dev",
            "FileVersion": "0.0.0.0"
          }
        }
      }
    }
  }
}
`, brand.Company, brand.AgentName, brand.Slug+"-agent", "Copyright (c) "+brand.Company, brand.Slug+"-agent.exe", brand.Name)
		if err := os.WriteFile(*winres, []byte(src), 0o644); err != nil { // #nosec G306 -- a source file
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
	if *wix {
		fmt.Printf("ProductName=%s\nAgentName=%s\nCompany=%s\nSlug=%s\nServiceName=%s\nSetupFolder=%s\nFolderName=%s\n", brand.Name, brand.AgentName, brand.Company, brand.Slug, brand.ServiceName, brand.SetupFolderName, brand.FolderName)
	}
}
